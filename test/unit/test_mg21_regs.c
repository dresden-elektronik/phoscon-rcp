    FLD(MG21_NVIC_ICER0, REF_FLD_CORE_NVIC_ICER0);
    FLD(MG21_NVIC_ICER1, REF_FLD_CORE_NVIC_ICER1);
    FLD(MG21_NVIC_ICPR0, REF_FLD_CORE_NVIC_ICPR0);
