/* test_mg21_regs.c — the ConBee III register transcription, checked against the part.
 *
 * src/hal/mg21/mg21_regs.h is this tree's own transcription of the EFR32MG21 register map:
 * block bases, register offsets inside blocks that are not dense, the field encodings the HAL
 * writes, and the interrupt numbers. A typo in a transcription does not look like a typo: a
 * wrong offset names a different register, a wrong shift writes into a neighbouring field, and
 * neither is visible in a suite of arithmetic. So the transcription is compared with a record
 * of what the part actually is.
 *
 * The record is `test/data/mg21_regs_ref.h`, generated by tools/mg21_regs_gold.py compiling
 * tools/mg21_regs_gold.c against the vendor's device headers, which read the layout out of the
 * vendor's own typedefs with offsetof. The record is checked in so this suite runs without a
 * reference tree present; regenerating it is the step that notices a part or SDK revision, and
 * the diff of a regenerated record is the review.
 *
 * The two sides keep different names on purpose: the record is REF_*, the transcription is
 * MG21_*, and the register blocks are different struct types, so a disagreement shows up as a
 * failed comparison rather than as a redefinition. */
