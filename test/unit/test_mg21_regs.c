    /* One byte per interrupt, four implemented bits: the group and bit selects are what let a
     * driver reach ISER/ICER for an IRQ above 31, and this board has IRQs up to 60. */
    TU_EQ(MG21_NVIC_GROUP(60), 1u);
    TU_EQ(MG21_NVIC_GROUP(11), 0u);
    TU_EQ(MG21_NVIC_BIT(43), 1uL << 11);
