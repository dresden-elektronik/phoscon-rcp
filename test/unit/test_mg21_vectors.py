"""test_mg21_vectors.py — the ConBee III vector table, checked slot by slot against the part.

`src/startup/startup_mg21.S` places 77 handler addresses in a fixed order, and the order is the
whole content of the file: an entry in the wrong slot hands one peripheral's interrupt to another
driver's handler, the driver reads a status register that never mentions its own event, and every
register write in it is aimed at the right block but the wrong moment. Nothing on a board reports
that, so the table is compared with `test/data/mg21_vectors.json`, generated by
tools/mg21_vectors_gold.py from the part's own `IRQn_Type` enum (docs/testing.md §5 audit G).

Three things are asserted: the table has one entry per slot the part defines; a handler this tree
names is at the slot the part names it for; and the interrupt numbers `src/hal/mg21/mg21_regs.h`
gives its drivers are the numbers the part gives the same peripherals. The startup file's own slot
comments are checked against their position too, because a comment that disagrees with its line is
how a table drifts.
"""
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
STARTUP = os.path.join(REPO, "src", "startup", "startup_mg21.S")
REGS = os.path.join(REPO, "src", "hal", "mg21", "mg21_regs.h")
TOOLCHAIN = os.path.join(REPO, "cmake", "arm-none-eabi-m33.cmake")
RECORD = os.path.join(REPO, "test", "data", "mg21_vectors.json")

FIRST_IRQ_SLOT = 16
DEFAULT_HANDLER = "def_handler"
ENTRY_ALIASES = {
    "NMI": "NonMaskableInt",
    "MemManage": "MemoryManagement",
}

LONG_RE = re.compile(r"^\s*\.long\s+([A-Za-z0-9_]+)\s*(?:/\*\s*(\d+)?:?([^*]*)\*/)?\s*$")
IRQ_DEFINE_RE = re.compile(r"^#define\s+MG21_IRQ_([A-Z0-9_]+)\s+\(?(-?\d+)u?\)?\s*$", re.M)

failures = 0


def check(ok, what, detail=""):
    global failures
    print(("  PASS  " if ok else "* FAIL* ") + what + (f" :: {detail}" if detail else ""))
    if not ok:
        failures += 1
    return ok


def our_table():
    entries = []
    with open(STARTUP, encoding="utf-8") as f:
        for line in f:
            m = LONG_RE.match(line.rstrip())
            if m is None:
                continue
            name, slot, _label = m.group(1), m.group(2), (m.group(3) or "").strip()
            entries.append((name, slot))
    return entries


def ours_at_slot(name, slot):
    if name == "_estack":
        return slot == 0
    if name == "Reset_Handler":
        return slot == 1
    if name == DEFAULT_HANDLER:
        return True
    stem = name[:-len("_Handler")] if name.endswith("_Handler") else name
    return ENTRY_ALIASES.get(stem, stem) == ours_name_for(slot)


OURS = {}


def ours_name_for(slot):
    return OURS[slot]


def main() -> int:
    for path in (STARTUP, REGS, TOOLCHAIN, RECORD):
        if not os.path.isfile(path):
            print(f"mg21_vectors: missing {path}", file=sys.stderr)
            return 2

    with open(RECORD, encoding="utf-8") as f:
        rec = json.load(f)
    table = rec["table"]

    check(len(table) == rec["first_irq_slot"] + rec["highest_irq"] + 1,
          "the record has one entry per slot the part defines",
          f"{len(table)} entries, IRQ 0..{rec['highest_irq']}")
    check(rec["first_irq_slot"] == FIRST_IRQ_SLOT,
          "IRQ n sits at table index 16 + n", f"record says {rec['first_irq_slot']}")

    entries = our_table()
    OURS.update({FIRST_IRQ_SLOT + n: name for n, name in enumerate(table[FIRST_IRQ_SLOT:])})
    OURS.update({i: name for i, name in enumerate(table[:FIRST_IRQ_SLOT])})

    check(len(entries) == len(table),
          "the startup table has the part's entry count",
          f"startup {len(entries)}, part {len(table)}")
    if len(entries) != len(table):
        print("mg21_vectors: table length differs, per-slot checks skipped")
        return 1

    # The startup labels its entries the way the SAMR21 startup does: core entries by table slot,
    # peripheral entries by IRQ number, which is slot - 16. A label that matches neither is a line
    # that has been moved without its comment.
    def labelMatches(i, slot):
        n = int(slot)
        return n == i if i < FIRST_IRQ_SLOT else n == i - FIRST_IRQ_SLOT

    mislabeled = [(i, slot) for i, (_, slot) in enumerate(entries)
                  if slot is not None and not labelMatches(i, slot)]
    check(not mislabeled, "every slot comment names the slot it sits in",
          f"mismatched at {mislabeled[:6]}" if mislabeled else "77 labels, 77 positions")

    wrong = []
    for i, (name, _) in enumerate(entries):
        if not ours_at_slot(name, i):
            wrong.append((i, name, table[i]))
    check(not wrong, "each handler the startup names is at the slot the part names it for",
          f"{wrong[:6]}" if wrong else f"{sum(1 for n, _ in entries if n != DEFAULT_HANDLER)} named handlers")

    defaults = sum(1 for n, _ in entries if n == DEFAULT_HANDLER)
    check(defaults > 0,
          "unused vectors are claimed, not left dangling",
          f"{defaults} entries fall into {DEFAULT_HANDLER}")

    with open(REGS, encoding="utf-8") as f:
        regs = f.read()
    bad = []
    for name, value in IRQ_DEFINE_RE.findall(regs):
        n = int(value)
        slot = FIRST_IRQ_SLOT + n
        want = {"USART0_RX": "USART0_RX", "USART0_TX": "USART0_TX", "WDOG0": "WDOG0",
                "SYSTICK": "SysTick", "PENDSV": "PendSV", "SVCALL": "SVCall",
                "HARDFAULT": "HardFault"}.get(name)
        if want is None:
            bad.append((name, "no rule for this constant"))
        elif slot < 0 or slot >= len(table) or table[slot] != want:
            bad.append((name, n, table[slot] if 0 <= slot < len(table) else "no slot"))
    check(not bad, "the interrupt numbers the HAL names are the part's numbers",
          f"{bad}" if bad else f"{len(IRQ_DEFINE_RE.findall(regs))} constants checked")

    with open(TOOLCHAIN, encoding="utf-8") as f:
        tc = f.read()
    check(".cpu cortex-m33" in open(STARTUP, encoding="utf-8").read(),
          "the startup declares the core the toolchain compiles for")
    check("-mcpu=cortex-m33" in tc, "the cb3 toolchain asks for the same core",
          "cmake/arm-none-eabi-m33.cmake")

    if failures:
        print(f"mg21_vectors: {failures} failure(s)")
        return 1
    print("mg21_vectors: the vector table matches the part, slot for slot")
    return 0


if __name__ == "__main__":
    sys.exit(main())
