/* mg21_regs_gold.c — reads the EFR32MG21 register layout out of the part's own headers.

Host tool, not firmware, and not built by the suites. Running it through tools/mg21_regs_gold.py
writes `test/data/mg21_regs_ref.h`, the checked-in record that test/unit/test_mg21_regs.c
compares this tree's transcription (`src/hal/mg21/mg21_regs.h`) against.

It is a program and not a table typed from a datasheet because the blocks are not dense. CMU's
SYSCLKCTRL is at +0x70 and its EM01GRPACLKCTRL at +0x120; HFXO0 starts at +0x10; GPIO's ports
are 48 bytes apart and its USART route arrays start at +0x5AC; USART0's CLKDIV occupies bits
22:3. Those are properties of the part, and the reliable way to read them is to let a compiler
say where the vendor's own typedef puts each register, and to quote the vendor's own field
macros by name.

The names this prints are the vendor's, prefixed REF_, so the record is greppable against the
headers it came from. The record is data under test/, and nothing in src/ includes it. */
