"""Generate the ConBee III radio back-end's data: the sequencer image and the register tables.

Writes three files of src/hal/mg21/ (docs/hardware_mg21.md §10.5 says where each value comes from):

  mg21_seq_image.c   the sequencer program of tools/mg21_seq.py, assembled - this tree's own code
  mg21_radio_cfg.c   the bring-up's register writes and the per-channel tune table

The register values are the configuration the vendor bring-up writes, as recorded from it in the MG21
research corpus (not part of this repository): the radio control blocks' writes of the
emulated bring-up log, in order, and the emulated channel tune per channel. Values only - no vendor
code - and only the part reception was shown to need: PROTIMER, the clock blocks, GPIO, SEQRAM and
FRCRAM are left out, and so are the vendor's own sequencer install, its storage and scratch registers
(read only by the vendor's sequence program, which this tree does not run) and every interrupt
enable (this back-end polls). A buffer address is kept as the index of the buffer; the driver
substitutes its own RAM.

    python3 tools/mg21_radio_gen.py                   # write the C files
    python3 tools/mg21_radio_gen.py --check           # exit 1 if the C files are not up to date
    python3 tools/mg21_radio_gen.py --json out.json   # the same tables, for a bench check
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(HERE))
import mg21_mon  # noqa: E402
import mg21_seq  # noqa: E402

CORPUS = REPO / "refs" / "mg21-radio-research" / "experiments" / "data"
OUT = REPO / "src" / "hal" / "mg21" / "own"
CHANNELS = range(11, 27)

BLOCKS = {"FRC": 0xB8004000, "AGC": 0xB800C000, "RFCRC": 0xB8010000, "MODEM": 0xB8014000,
          "SYNTH": 0xB8018000, "RAC": 0xB8020000, "BUFC": 0x54004000}
KEEP_BLOCKS = set(BLOCKS)
REV = {}
for (blk, name), off in mg21_mon.OFFS.items():
    REV.setdefault(blk, {})[off] = name

# Registers of the kept blocks that the table leaves out, by name, in every alias window.
DROP = {("RAC", n) for n in ("SR0", "SR1", "SR2", "SR3", "VECTADDR", "SEQCTRL", "R6", "IF", "IEN",
                             "RXENSRCEN")}
DROP |= {("RAC", f"SCRATCH{i}") for i in range(8)}
DROP |= {(b, n) for b in BLOCKS for n in ("IF", "IEN")}
BUF_ADDR = {f"BUF{n}_ADDR": n for n in range(4)}
ALIAS = {0: "", 1: "_SET", 2: "_CLR", 3: "_TGL"}


def name(addr):
    for blk, base in BLOCKS.items():
        if base <= addr < base + 0x4000:
            off = addr - base
            return blk, REV[blk].get(off & 0xFFF, f"0x{off & 0xFFF:03X}"), off >> 12
    return None, None, None


def bringup(log):
    """[(address, value, comment)] in the bring-up's order."""
    out = []
    for addr, val, size, _pc in log:
        blk, reg, alias = name(addr)
        if blk not in KEEP_BLOCKS or (blk, reg) in DROP:
            continue
        if blk == "RAC" and reg == "CTRL" and val == 0x1:  # FORCEDISABLE: the driver's install owns it
            continue
        if blk == "FRC" and reg == "CMD" and val == 0x200:  # CONVINIT: part of the driver's install
            continue
        assert size == 4
        if reg in BUF_ADDR:
            out.append((addr, BUF_ADDR[reg], f"BUFC.{reg}{ALIAS[alias]}: buffer {BUF_ADDR[reg]}"))
            continue
        out.append((addr, val, f"{blk}.{reg}{ALIAS[alias]}"))
    return out


def tune():
    """Per channel: MODEM.DIGMIXCTRL set value, MODEM.SRCCHF set value, RAC.XORETIMECTRL."""
    rows = []
    for ch in CHANNELS:
        w = {a: v for a, v, _s in json.loads((CORPUS / "tune" / f"tune{ch}.json").read_text())["writes"]}
        rows.append((ch, w[mg21_mon.resolve("MODEM.DIGMIXCTRL.SET")], w[mg21_mon.resolve("MODEM.SRCCHF.SET")],
                     w[mg21_mon.resolve("RAC.XORETIMECTRL")]))
    return rows


# Every generated file carries the tree's licence header.
SPDX = "/* SPDX-License-Identifier: BSD-3-Clause\n * Copyright (c) 2026 dresden elektronik ingenieurtechnik gmbh */\n"

HEADER = """/* {name} — generated by tools/mg21_radio_gen.py; do not edit, regenerate.
 *
 * {what}
 * Provenance and the bench evidence: docs/hardware_mg21.md §10.5. */
"""


def seq_c():
    words, entries, _ = mg21_seq.build()
    lines = [SPDX + HEADER.format(name="mg21_seq_image.c",
                           what="The radio sequencer program of tools/mg21_seq.py, assembled: this tree's own code, "
                                "written against\n * the instruction encodings the bench settled."),
             "#include <stdint.h>\n", '#include "mg21_radio_cfg.h"\n',
             "/* " + ", ".join(f"{k} at +0x{v:04X}" for k, v in entries.items()) + " */",
             f"const uint32_t Mg21Seq_Image[MG21_SEQ_IMAGE_WORDS] = {{"]
    for i in range(0, len(words), 6):
        lines.append("    " + ", ".join(f"0x{w:08X}u" for w in words[i:i + 6]) + ",")
    lines.append("};\n")
    return "\n".join(lines), len(words)


def cfg_c(writes, rows):
    lines = [SPDX + HEADER.format(name="mg21_radio_cfg.c",
                           what="Register values of the vendor bring-up and channel tune, as recorded in the MG21 research "
                                "corpus:\n * values only, the subset reception needs, in the bring-up's order."),
             "#include <stdint.h>\n", '#include "mg21_radio_cfg.h"\n',
             "const Mg21RadioCfg_Write Mg21RadioCfg_Bringup[MG21_RADIO_CFG_BRINGUP_WRITES] = {"]
    for addr, val, comment in writes:
        lines.append(f"    {{0x{addr:08X}u, 0x{val:08X}u}}, /* {comment} */")
    lines += ["};\n", "const Mg21RadioCfg_Channel Mg21RadioCfg_Channels[MG21_RADIO_CFG_CHANNELS] = {"]
    for ch, dig, src, xo in rows:
        lines.append(f"    {{0x{dig:08X}u, 0x{src:08X}u, 0x{xo:04X}u}}, /* channel {ch} */")
    lines.append("};\n")
    return "\n".join(lines)


# The transmit settings the stock deCONZ firmware runs at 10 dBm, read from its registers while it
# transmitted (docs/hardware_mg21.md §10.5): the ramp rates, and the level that stands both in
# RAC.PACTRL[23:16] and in each of MODEM.RAMPLEV's three ramp levels.
TX_RAMPCTRL = 0x666
TX_LEVEL_10DBM = 0x59


def cfg_h(nwrites, nwords):
    return SPDX + f"""/* mg21_radio_cfg.h — generated by tools/mg21_radio_gen.py; do not edit, regenerate.
 *
 * The data the ConBee III radio back-end carries: the sequencer image (mg21_seq_image.c, this tree's
 * own program) and the register tables (mg21_radio_cfg.c, values of the vendor bring-up). Where each
 * comes from, and what the bench showed of it: docs/hardware_mg21.md §10.5. */
#ifndef MG21_RADIO_CFG_H
#define MG21_RADIO_CFG_H

#include <stdint.h>

#define MG21_SEQ_IMAGE_WORDS {nwords}u
#define MG21_RADIO_CFG_BRINGUP_WRITES {nwrites}u
#define MG21_RADIO_CFG_CHANNELS 16u
#define MG21_RADIO_CFG_CHANNEL_FIRST 11u

/* The sequencer program's cells the CPU fills, as SEQRAM byte offsets (tools/mg21_seq.py): the
 * transmission's PACTRL[23:16] shifted into place, and non-zero to turn to receive right after it. */
#define MG21_SEQ_PA_CELL 0x{mg21_seq.PA_CELL:04X}u
#define MG21_SEQ_RX_AFTER_TX_CELL 0x{mg21_seq.RX_AFTER_TX_CELL:04X}u

/* The stock firmware's transmit ramp rates and its 10 dBm level (docs/hardware_mg21.md §10.5). */
#define MG21_RADIO_CFG_TX_RAMPCTRL 0x{TX_RAMPCTRL:03X}u
#define MG21_RADIO_CFG_TX_LEVEL_10DBM 0x{TX_LEVEL_10DBM:02X}u

/* One register write of the bring-up. A write to a BUFC buffer-address register carries the buffer's
 * index (0..3) as its value: the driver writes its own RAM's address there. */
typedef struct
{{
    uint32_t addr;
    uint32_t value;
}} Mg21RadioCfg_Write;

/* The channel tune's channel-dependent values (the rest is constant or computed, mg21_phy.h). */
typedef struct
{{
    uint32_t digMix;   /* MODEM.DIGMIXCTRL, the DIGMIXFREQ field */
    uint32_t srcChf;   /* MODEM.SRCCHF, its fields outside the kept 0xF0000700 */
    uint16_t xoRetime; /* RAC.XORETIMECTRL */
}} Mg21RadioCfg_Channel;

extern const uint32_t Mg21Seq_Image[MG21_SEQ_IMAGE_WORDS];
extern const Mg21RadioCfg_Write Mg21RadioCfg_Bringup[MG21_RADIO_CFG_BRINGUP_WRITES];
extern const Mg21RadioCfg_Channel Mg21RadioCfg_Channels[MG21_RADIO_CFG_CHANNELS];

#endif /* MG21_RADIO_CFG_H */
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--json")
    a = ap.parse_args()
    seq, nwords = seq_c()
    files = {"mg21_seq_image.c": seq}
    if CORPUS.exists():
        log = json.loads((CORPUS / "init.json").read_text())["writes"]
        writes, rows = bringup(log), tune()
        files["mg21_radio_cfg.c"] = cfg_c(writes, rows)
        files["mg21_radio_cfg.h"] = cfg_h(len(writes), nwords)
        if a.json:
            Path(a.json).write_text(json.dumps({"bringup": [(w[0], w[1]) for w in writes],
                                                "channels": rows, "image": mg21_seq.build()[0]}))
    elif not a.check:
        sys.exit(f"the research corpus is not here ({CORPUS}): only --check of the sequencer image runs")
    stale = [f for f, text in files.items() if not (OUT / f).exists() or (OUT / f).read_text() != text]
    if a.check:
        for f in stale:
            print(f"{f}: not what tools/mg21_radio_gen.py generates", file=sys.stderr)
        sys.exit(1 if stale else 0)
    for f, text in files.items():
        (OUT / f).write_text(text)
    print("wrote " + ", ".join(files) + f" ({len(files.get('mg21_radio_cfg.c', '').splitlines())} lines of tables)")


if __name__ == "__main__":
    main()
