"""Regenerate the ConBee III vector-order record that the mg21_vectors suite checks startup against.

`test/data/mg21_vectors.json` is the order the part's interrupt numbers occupy in the vector table:
IRQ number n sits at table index 16 + n, and a core exception with CMSIS number -k sits at 16 - k,
which is the ARMv8-M numbering the startup file has to lay out. The names come from the part's own
device header (`IRQn_Type` in `efr32mg21a010f1024im32.h`), never from a datasheet table, because the
question this record answers - which slot is which interrupt - is the one a transcription typo gets
silently wrong.

    SDK=<simplicity_sdk_2024.12.1> python3 tools/mg21_vectors_gold.py

The SDK is not part of this repository, so the record is checked in and the suite runs from a fresh clone with no
reference tree present. Regenerate after a part or SDK change and read the diff.
"""
import json
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "test" / "data" / "mg21_vectors.json"
PART_HEADER = "efr32mg21a010f1024im32.h"
SHAPES = ["Device/Include", "platform/Device/SiliconLabs/EFR32MG21/Include"]

FIRST_IRQ_SLOT = 16
ENTRY_NAMES = {
    0: "initial_sp",
    1: "Reset_Handler",
}
ENUM_RE = re.compile(r"^\s*([A-Za-z0-9_]+_IRQn)\s*=\s*(-?\d+)\s*,", re.M)


def find_header(root: Path):
    for shape in SHAPES:
        cand = root / shape / PART_HEADER
        if cand.is_file():
            return cand
    return None


def main() -> int:
    root = os.environ.get("SDK")
    if not root:
        print("mg21_vectors_gold: set SDK=<Simplicity SDK tree>", file=sys.stderr)
        return 2

    header = find_header(Path(root))
    if header is None:
        print(f"mg21_vectors_gold: {PART_HEADER} not found under {root}", file=sys.stderr)
        return 2

    text = header.read_text(errors="replace")
    found = re.search(r"typedef enum\s+\w*\s*\{(.*?)\}\s*IRQn_Type;", text, re.S)
    if found is None:
        print("mg21_vectors_gold: no IRQn_Type enum in the part header", file=sys.stderr)
        return 1
    body = found.group(1)

    core = {}
    irq = {}
    for name, value in ENUM_RE.findall(body):
        base = name[: -len("_IRQn")]
        n = int(value)
        if n < 0:
            core[FIRST_IRQ_SLOT + n] = base
        else:
            irq[n] = base

    highest = max(irq)
    table = []
    for slot in range(FIRST_IRQ_SLOT):
        table.append(ENTRY_NAMES.get(slot) or core.get(slot) or "reserved")
    for n in range(highest + 1):
        table.append(irq[n])

    OUT.write_text(
        json.dumps(
            {
                "note": "generated by tools/mg21_vectors_gold.py from the part's own IRQn_Type; "
                "index 0 is the initial stack pointer and 1 the reset vector, 2..15 are core "
                "exceptions at 16 + the CMSIS number, and 16.. are IRQ n at 16 + n. A slot named "
                "'reserved' is one the part's header does not name (ARMv8-M reserves them; slot 7 is "
                "SecureFault, which this part's enum leaves unnamed).",
                "spdx": "BSD-3-Clause",
                "copyright": "Copyright (c) 2026 dresden elektronik ingenieurtechnik gmbh",
                "source": str(header.relative_to(root)),
                "part": PART_HEADER,
                "entry_count": len(table),
                "first_irq_slot": FIRST_IRQ_SLOT,
                "highest_irq": highest,
                "table": table,
            },
            indent=2,
        )
        + "\n"
    )
    print(f"mg21_vectors_gold: wrote {len(table)} entries (highest IRQ {highest}) to "
          f"{OUT.relative_to(REPO)} from {root}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
